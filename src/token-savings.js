import { closeSync, openSync, readdirSync, readSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

// The share of a project's text that TDK generated, so the model never had to write it. This is an estimate, not a billing figure:
// tokens are approximated as characters / 4, and only text files are counted.
const SKIP_DIRS = new Set(["node_modules", ".git", ".next", "dist", "build", "target", "__pycache__", ".venv"]);
const SKIP_FILES = new Set(["bun.lock", "bun.lockb", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock", "go.sum"]);
const MAX_FILE_BYTES = 512 * 1024;
const MAX_FILES = 5000;
const CACHE_MS = 60_000;

const cache = new Map();

export function estimateTokens(text) {
  return Math.ceil(text.length / 4);
}

// Generated: any .autogenerated folder, TDK's own output under .tdk/.tdk-out, and the root Tiltfile and docker-compose.yml.
export function isGeneratedPath(relativePath) {
  const parts = relativePath.split(sep);
  if (parts.includes(".autogenerated")) return true;
  if (parts[0] === ".tdk" && parts[1] === ".tdk-out") return true;
  return parts.length === 1 && (parts[0] === "Tiltfile" || parts[0] === "docker-compose.yml");
}

function isText(path) {
  const fd = openSync(path, "r");
  try {
    const buffer = Buffer.alloc(512);
    const read = readSync(fd, buffer, 0, buffer.length, 0);
    return !buffer.subarray(0, read).includes(0);
  } finally {
    closeSync(fd);
  }
}

// Walks the project and totals the estimated tokens on each side. Limits keep a huge tree from stalling the dashboard.
export function measureTokenSavings(root) {
  let generated = 0;
  let authored = 0;
  let files = 0;
  const visit = (directory) => {
    if (files >= MAX_FILES) return;
    let entries;
    try {
      entries = readdirSync(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (files >= MAX_FILES) return;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) visit(path);
        continue;
      }
      if (!entry.isFile() || SKIP_FILES.has(entry.name)) continue;
      try {
        const size = statSync(path).size;
        if (size > MAX_FILE_BYTES || !isText(path)) continue;
        const tokens = estimateTokens(readFileSync(path, "utf8"));
        files += 1;
        if (isGeneratedPath(relative(root, path))) generated += tokens;
        else authored += tokens;
      } catch {}
    }
  };
  visit(root);
  const total = generated + authored;
  return { generatedTokens: generated, authoredTokens: authored, savedPct: total ? Math.round((generated / total) * 100) : null };
}

// Cached per project root for a minute, so the status poll does not re-walk the tree every few seconds.
export function tokenSavings(root, now = Date.now()) {
  const cached = cache.get(root);
  if (cached && now - cached.at < CACHE_MS) return cached.value;
  const value = measureTokenSavings(root);
  cache.set(root, { at: now, value });
  return value;
}
